// Generates the .vscodeignore un-ignore block for node-llama-cpp's full
// runtime (production) dependency closure, discovered fresh by walking
// installed package.json files directly off disk with fs (NOT via
// require()-based resolution, which several of these packages block for
// their own package.json via a strict "exports" map — confirmed
// 2026-08-25, ERR_PACKAGE_PATH_NOT_EXPORTED on node-llama-cpp itself).
//
// Why generate this instead of hand-maintaining a static list in
// .vscodeignore: node-llama-cpp's dependency closure is large (91 packages
// as of 2026-08-25, discovered via this exact walk) and can change on any
// version bump. Hand-typing and hand-updating a list that size invites
// transcription errors and drift — exactly what caused the "Cannot find
// package 'lifecycle-utils'" failure that led to writing this script in the
// first place (that was found one broken install at a time; this discovers
// the COMPLETE closure in one pass, every time).
//
// Deliberately follows only `dependencies`, not `optionalDependencies` —
// the native platform-binary packages (@node-llama-cpp/win-x64 etc.,
// @reflink/*) are declared as optionalDependencies by node-llama-cpp, so
// they never appear in this walk. Those stay a separate, deliberately
// hand-curated block in .vscodeignore (see prune-unused-native-variants.js
// for why only SOME platform variants are wanted, which an automated walk
// has no way to know).
//
// Wired into `npm run package`, before `vsce package`, so .vscodeignore is
// always regenerated against whatever is currently installed. Writes the
// generated block into .vscodeignore between the BEGIN/END GENERATED
// markers, leaving every hand-written rule elsewhere in the file untouched.

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const NODE_MODULES = path.join(ROOT, "node_modules");
const VSCODEIGNORE = path.join(ROOT, ".vscodeignore");

const BEGIN_MARKER =
  "# BEGIN GENERATED node-llama-cpp dependency closure (scripts/generate-native-deps-ignore.js — DO NOT hand-edit)";
const END_MARKER = "# END GENERATED node-llama-cpp dependency closure";

function walk(name, seen) {
  if (seen.has(name)) return;
  seen.add(name);
  const pkgPath = path.join(NODE_MODULES, ...name.split("/"), "package.json");
  if (!fs.existsSync(pkgPath)) {
    console.warn(
      `[generate-native-deps-ignore] WARNING: expected dependency "${name}" ` +
        `not found at ${pkgPath} — skipping. This usually means a version ` +
        `conflict put it in a nested node_modules instead of the flat top ` +
        `level; if the packaged extension fails to load node-llama-cpp, ` +
        `check for this package's actual location and extend this script.`
    );
    return;
  }
  const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf8"));
  for (const dep of Object.keys(pkg.dependencies || {})) {
    walk(dep, seen);
  }
}

function unignoreLinesFor(name) {
  if (name.startsWith("@")) {
    const [scope, pkg] = name.split("/");
    return [
      `!node_modules/${scope}`,
      `!node_modules/${scope}/${pkg}`,
      `!node_modules/${scope}/${pkg}/**`,
    ];
  }
  return [`!node_modules/${name}`, `!node_modules/${name}/**`];
}

function main() {
  const seen = new Set();
  walk("node-llama-cpp", seen);
  seen.delete("node-llama-cpp"); // handled by its own hand-written block, not this generated one

  const names = [...seen].sort();
  const lines = [
    BEGIN_MARKER,
    `# ${names.length} packages, regenerated by re-running this script.`,
    "# Re-run after any node-llama-cpp version bump: `node scripts/generate-native-deps-ignore.js`",
    "# (or just `npm run package`, which runs it automatically first).",
    ...names.flatMap(unignoreLinesFor),
    END_MARKER,
  ];

  const current = fs.readFileSync(VSCODEIGNORE, "utf8");
  const beginIdx = current.indexOf(BEGIN_MARKER);
  const endIdx = current.indexOf(END_MARKER);

  let next;
  if (beginIdx === -1 || endIdx === -1) {
    next = current.replace(/\n*$/, "\n\n") + lines.join("\n") + "\n";
  } else {
    const before = current.slice(0, beginIdx);
    const after = current.slice(endIdx + END_MARKER.length);
    next = before + lines.join("\n") + after;
  }

  fs.writeFileSync(VSCODEIGNORE, next);
  console.log(
    `[generate-native-deps-ignore] Wrote ${names.length} package un-ignore rules to .vscodeignore.`
  );
}

main();
